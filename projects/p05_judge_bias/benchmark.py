"""Run every pair in both orders under every judge prompt, and write RESULTS.md.

    uv run python -m projects.p05_judge_bias.benchmark

Two pair types, and they answer different questions:

    tie      two equally correct answers. There is nothing to detect, so any systematic
             preference is bias. This is where position and length effects are measured.
    quality  one answer contains a real error. This is where judging ability is measured.

Both are needed. A judge with no bias and no ability scores perfectly on the first table and
uselessly on the second, and the reverse is also possible.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p05_judge_bias.answers import CORPUS, quality_pairs, tie_pairs
from projects.p05_judge_bias.judge import PROMPTS, BothOrders, compare_both_orders
from shared.llm import Ledger, installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"


@dataclass
class Cell:
    prompt: str
    pair_type: str
    n: int = 0
    consistent: int = 0
    flipped: int = 0
    position_a: int = 0  # chose whatever sat first, both times
    position_b: int = 0
    ties: int = 0  # said TIE at least once
    tie_both: int = 0  # said TIE in both orders
    unparsed: int = 0
    #: Among pairs judged consistently, how often the longer answer won. Only meaningful on
    #: tie pairs, where the answers are equally correct.
    consistent_verbose: int = 0
    consistent_total: int = 0
    #: Among consistently judged quality pairs, how often the correct answer won.
    consistent_correct: int = 0
    examples: list = field(default_factory=list)

    @property
    def flip_rate(self) -> float:
        return self.flipped / self.n if self.n else 0.0

    @property
    def position_rate(self) -> float:
        """How often the verdict was determined by position rather than by content."""
        return (self.position_a + self.position_b) / self.n if self.n else 0.0

    @property
    def decisive(self) -> float:
        """Pairs where the judge gave the same answer in both orders — usable verdicts."""
        return self.consistent / self.n if self.n else 0.0


def tally(prompt: str, pair_type: str, results: list[BothOrders]) -> Cell:
    cell = Cell(prompt=prompt, pair_type=pair_type, n=len(results))
    for r in results:
        if not r.forward.chose or not r.reversed.chose:
            cell.unparsed += 1
        cell.consistent += int(r.consistent)
        cell.flipped += int(r.flipped)
        cell.position_a += int(r.chose_first_both_times)
        cell.position_b += int(r.chose_second_both_times)
        said_tie = [v for v in (r.forward, r.reversed) if v.raw == "TIE"]
        cell.ties += int(bool(said_tie))
        cell.tie_both += int(len(said_tie) == 2)

        if r.consistent and r.forward.chose != "tie":
            cell.consistent_total += 1
            if r.forward.chose == "verbose":
                cell.consistent_verbose += 1
            if r.forward.chose == "concise":
                cell.consistent_correct += 1

        if len(cell.examples) < 3:
            cell.examples.append(
                {
                    "question": r.question.id,
                    "forward": (f"{r.forward.first} first -> {r.forward.raw} ({r.forward.chose})"),
                    "reversed": (
                        f"{r.reversed.first} first -> {r.reversed.raw} ({r.reversed.chose})"
                    ),
                }
            )
    return cell


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def render(cells: list[Cell], elapsed: float, repeats: int, model: str) -> str:
    by = {(c.prompt, c.pair_type): c for c in cells}
    out = ["# Results\n"]
    out.append("Generated by `projects/p05_judge_bias/benchmark.py`. Do not edit.\n")
    out.append(
        f"{len(PROMPTS)} judge prompts x {len(CORPUS)} questions x 2 pair types x 2 orders "
        f"x {repeats} repeats on `{model}`. {elapsed / 60:.1f} minutes.\n"
    )

    out.append("\n## Tie pairs: two equally correct answers\n")
    out.append(
        "There is no quality difference here, so the correct verdict is a tie and every "
        "preference recorded is bias. `position` is the share where the judge picked the same "
        "**slot** in both orders — a verdict decided by where the answer sat.\n"
    )
    out.append("| judge prompt | flipped on reorder | position-decided | said tie | longer won |")
    out.append("|---|---|---|---|---|")
    for p in PROMPTS:
        c = by.get((p, "tie"))
        if not c:
            continue
        out.append(
            f"| `{p}` | {_pct(c.flipped, c.n)} | {_pct(c.position_a + c.position_b, c.n)} "
            f"| {_pct(c.ties, c.n)} "
            f"| {_pct(c.consistent_verbose, c.consistent_total)} |"
        )

    out.append("\n## Quality pairs: one answer is wrong\n")
    out.append(
        "`decisive` is the share of pairs the judge answered the same way in both orders; "
        "everything else is a coin flip dressed as a verdict. `correct when decisive` is "
        "accuracy over those.\n"
    )
    out.append("| judge prompt | flipped on reorder | decisive | correct when decisive |")
    out.append("|---|---|---|---|")
    for p in PROMPTS:
        c = by.get((p, "quality"))
        if not c:
            continue
        out.append(
            f"| `{p}` | {_pct(c.flipped, c.n)} | {_pct(c.consistent, c.n)} "
            f"| {_pct(c.consistent_correct, c.consistent_total)} |"
        )

    out.append("\n## Verdicts, as recorded\n")
    for p in PROMPTS:
        for t in ("tie", "quality"):
            c = by.get((p, t))
            if not c or not c.examples:
                continue
            out.append(f"\n**`{p}` / {t}**\n")
            for e in c.examples:
                out.append(f"- `{e['question']}`: {e['forward']} | {e['reversed']}")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    parser.add_argument("--repeats", type=int, default=1)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    book = Ledger()
    cells: list[Cell] = []

    for prompt in PROMPTS:
        for pair_type, pairs in (("tie", tie_pairs()), ("quality", quality_pairs())):
            print(f"  {prompt} / {pair_type}", flush=True)
            results: list[BothOrders] = []
            for question, a, b in pairs:
                for _ in range(args.repeats):
                    try:
                        results.append(
                            compare_both_orders(
                                question, a, b, prompt=prompt, model=model, ledger=book
                            )
                        )
                    except Exception as exc:
                        print(f"    ! {question.id}: {exc}", file=sys.stderr)
            cells.append(tally(prompt, pair_type, results))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(c) for c in cells], indent=2), encoding="utf-8")
    RESULTS.write_text(render(cells, elapsed, args.repeats, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}  ({book.n_calls} model calls)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
