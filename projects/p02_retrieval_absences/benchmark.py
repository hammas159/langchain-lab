"""Run every paper through every retrieval strategy and write RESULTS.md.

    uv run python -m projects.p02_retrieval_absences.benchmark

The grid is small on purpose — 12 papers by a handful of strategies — because the effect being
measured is large and does not need a big N to see. What it does need is the `full_context`
control, which is the same model, schema and prompt with no retriever in the way.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from projects.p01_structured_output.schemas import LADDER
from projects.p02_retrieval_absences.papers import PAPERS
from projects.p02_retrieval_absences.pipeline import Result, run
from shared.llm import installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"

#: label -> kwargs for `pipeline.run`
STRATEGIES: dict[str, dict] = {
    "full_context": {"strategy": "full_context"},
    "single_query_k4": {"strategy": "single_query", "k": 4},
    "single_query_k8": {"strategy": "single_query", "k": 8},
    "per_field_n1": {"strategy": "per_field", "per_field_k": 1},
    "per_field_n2": {"strategy": "per_field", "per_field_k": 2},
}


@dataclass
class Row:
    strategy: str
    n_papers: int
    recall: float
    context_words: float
    valid: float
    grounded_correct: int
    grounded_wrong: int
    phantom: int
    lucky_phantom: int
    honest_null: int
    fabricated: int
    true_null: int
    missed: int
    n_withheld: int
    n_silent: int
    phantom_rate: float
    fabrication_rate: float
    accuracy: float
    seconds: float


def summarise(label: str, results: list[Result]) -> Row:
    counts = {
        v: sum(r.count(v) for r in results)
        for v in (
            "grounded_correct",
            "grounded_wrong",
            "phantom",
            "lucky_phantom",
            "honest_null",
            "fabricated",
            "true_null",
            "missed",
        )
    }
    n_withheld = sum(r.n_withheld for r in results)
    n_silent = counts["fabricated"] + counts["true_null"]
    n_fields = sum(len(r.outcomes) for r in results)
    # A field is "right" if it matches ground truth, however it got there. `lucky_phantom` is
    # counted here because it is right, and excluded from grounded_correct because it is not
    # grounded — keeping both numbers visible is the point.
    correct = counts["grounded_correct"] + counts["lucky_phantom"] + counts["true_null"]

    return Row(
        strategy=label,
        n_papers=len(results),
        recall=sum(r.retrieved.recall for r in results) / len(results),
        context_words=sum(r.context_words for r in results) / len(results),
        valid=sum(r.valid for r in results) / len(results),
        n_withheld=n_withheld,
        n_silent=n_silent,
        phantom_rate=(counts["phantom"] + counts["lucky_phantom"]) / n_withheld
        if n_withheld
        else 0.0,
        fabrication_rate=counts["fabricated"] / n_silent if n_silent else 0.0,
        accuracy=correct / n_fields if n_fields else 0.0,
        seconds=sum(r.seconds for r in results),
        **counts,
    )


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def render(rows: list[Row], elapsed: float) -> str:
    out = ["# Results\n"]
    out.append("Generated by `projects/p02_retrieval_absences/benchmark.py`. Do not edit.\n")
    out.append(f"{len(rows)} strategies x {rows[0].n_papers} papers, {elapsed / 60:.1f} minutes.\n")

    out.append("\n## Retrieval, and what it costs\n")
    out.append(
        "`recall` is the share of fields whose evidence reached the model. `phantom rate` is, "
        "of the fields the paper states but retrieval withheld, how often the model produced a "
        "value anyway.\n"
    )
    out.append("| strategy | context | recall | accuracy | phantom rate | phantoms |")
    out.append("|---|---|---|---|---|---|")
    for r in rows:
        out.append(
            f"| `{r.strategy}` | {r.context_words:.0f} w | {_pct(r.recall)} | "
            f"{_pct(r.accuracy)} | {_pct(r.phantom_rate)} | "
            f"{r.phantom + r.lucky_phantom} of {r.n_withheld} |"
        )

    out.append("\n## Every outcome, counted\n")
    out.append(
        "| strategy | grounded ok | grounded wrong | phantom | lucky phantom | honest null | "
        "fabricated | true null | missed |"
    )
    out.append("|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        out.append(
            f"| `{r.strategy}` | {r.grounded_correct} | {r.grounded_wrong} | {r.phantom} | "
            f"{r.lucky_phantom} | {r.honest_null} | {r.fabricated} | {r.true_null} | "
            f"{r.missed} |"
        )

    out.append(
        "\n`fabricated` is project 01's sense: the paper is genuinely silent and the model "
        "supplied a value. `phantom` is new here: the paper states it, retrieval did not fetch "
        "it, and the model supplied a value regardless.\n"
    )
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    parser.add_argument("--level", default="L4_constrained")
    parser.add_argument("--limit", type=int, default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2

    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    schema = LADDER[args.level]
    papers = PAPERS[: args.limit]

    started = time.perf_counter()
    rows: list[Row] = []
    for label, kwargs in STRATEGIES.items():
        print(f"  {label}", flush=True)
        results = []
        for paper in papers:
            try:
                results.append(run(paper, schema, model=model, **kwargs))
            except Exception as exc:
                print(f"    ! {paper.id}: {type(exc).__name__}: {exc}", file=sys.stderr)
        if results:
            rows.append(summarise(label, results))
    elapsed = time.perf_counter() - started

    RAW.write_text(json.dumps([asdict(r) for r in rows], indent=2), encoding="utf-8")
    RESULTS.write_text(render(rows, elapsed), encoding="utf-8")
    print(f"\nwrote {RESULTS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
