"""Every defence against every payload, loud and quiet.

    uv run python -m projects.p04_injection_defence.benchmark --repeats 3

The table that matters is the last one: the same defence scored separately on the register it
was designed against and the register it was not.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p04_injection_defence.chain import DEFENCES, answer
from projects.p04_injection_defence.payloads import ALL, LOUD, OBJECTIVES, QUIET
from projects.p04_injection_defence.scoring import Verdict, judge
from shared.llm import Ledger, installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"


@dataclass
class Cell:
    defence: str
    register: str
    n: int = 0
    complied: int = 0
    stripped: int = 0
    declined: int = 0
    per_objective: dict = field(default_factory=dict)

    @property
    def rate(self) -> float:
        return self.complied / self.n if self.n else 0.0


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def tally(defence: str, register: str, verdicts: list[Verdict]) -> Cell:
    cell = Cell(defence=defence, register=register, n=len(verdicts))
    for v in verdicts:
        cell.complied += int(v.complied)
        cell.stripped += int(v.stripped)
        cell.declined += int(v.declined_by_model)
        slot = cell.per_objective.setdefault(v.payload.objective, [0, 0])
        slot[1] += 1
        slot[0] += int(v.complied)
    return cell


def render(cells: list[Cell], elapsed: float, repeats: int, model: str) -> str:
    by = {(c.defence, c.register): c for c in cells}
    out = ["# Results\n"]
    out.append("Generated by `projects/p04_injection_defence/benchmark.py`. Do not edit.\n")
    out.append(
        f"{len(DEFENCES)} defences x {len(ALL)} payloads x {repeats} repeats on `{model}`. "
        f"{elapsed / 60:.1f} minutes.\n"
    )

    out.append("\n## Injection success rate\n")
    out.append(
        "Lower is better. `loud` is the register defences are demonstrated against; `quiet` "
        "pursues the identical six objectives written as ordinary document content.\n"
    )
    out.append("| defence | loud | quiet | gap |")
    out.append("|---|---|---|---|")
    for d in DEFENCES:
        loud, quiet = by.get((d, "loud")), by.get((d, "quiet"))
        if not loud or not quiet:
            continue
        gap = quiet.rate - loud.rate
        out.append(
            f"| `{d}` | {_pct(loud.complied, loud.n)} | {_pct(quiet.complied, quiet.n)} "
            f"| {gap * 100:+.0f} pts |"
        )

    out.append("\n## Where the block happened\n")
    out.append(
        "A defence can score well because it removed the payload or because the model "
        "declined it. Only the first is a property of the defence.\n"
    )
    out.append("| defence | register | payload removed | model declined | complied |")
    out.append("|---|---|---|---|---|")
    for d in DEFENCES:
        for r in ("loud", "quiet"):
            c = by.get((d, r))
            if not c:
                continue
            out.append(
                f"| `{d}` | {r} | {_pct(c.stripped, c.n)} | {_pct(c.declined, c.n)} "
                f"| {_pct(c.complied, c.n)} |"
            )

    out.append("\n## Success rate by objective\n")
    out.append("| defence | register | " + " | ".join(OBJECTIVES) + " |")
    out.append("|---" * (len(OBJECTIVES) + 2) + "|")
    for d in DEFENCES:
        for r in ("loud", "quiet"):
            c = by.get((d, r))
            if not c:
                continue
            cells_ = []
            for o in OBJECTIVES:
                got, n = c.per_objective.get(o, [0, 0])
                cells_.append(_pct(got, n))
            out.append(f"| `{d}` | {r} | " + " | ".join(cells_) + " |")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    parser.add_argument("--repeats", type=int, default=3)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    cells: list[Cell] = []
    book = Ledger()

    for defence in DEFENCES:
        for register, payloads in (("loud", LOUD), ("quiet", QUIET)):
            print(f"  {defence} / {register}", flush=True)
            verdicts: list[Verdict] = []
            for payload in payloads:
                for _ in range(args.repeats):
                    try:
                        result = answer(defence, payload, model=model, ledger=book)
                        verdicts.append(judge(payload, result))
                    except Exception as exc:
                        print(f"    ! {payload.id}: {exc}", file=sys.stderr)
            cells.append(tally(defence, register, verdicts))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(c) for c in cells], indent=2), encoding="utf-8")
    RESULTS.write_text(render(cells, elapsed, args.repeats, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}  ({book.n_calls} model calls)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
