"""Run the grid: strategies x models x schema levels x abstracts.

Writes `RESULTS.md` next to this file. Every number in the project README comes from a run of
this, and nothing in the README is written by hand.

    uv run python -m projects.p01_structured_output.benchmark --quick
    uv run python -m projects.p01_structured_output.benchmark --full

`--quick` is one model and two levels, for checking the harness works. `--full` is the grid
that produces the reported table and takes a while: it is 4 strategies x 5 models x 5 levels
x 12 abstracts, and `error_feedback` may make up to three calls each.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from projects.p01_structured_output.corpus import CORPUS
from projects.p01_structured_output.schemas import LADDER
from projects.p01_structured_output.scoring import Aggregate, score
from projects.p01_structured_output.strategies import STRATEGIES
from shared.llm import Ledger, installed_tags, server_is_up
from shared.models import with_role

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"


@dataclass
class Cell:
    strategy: str
    model: str
    level: str
    n: int
    validity: float
    accuracy: float
    fabrication_rate: float
    omission_rate: float
    n_nullable: int
    n_fabricated: int
    calls: int
    seconds: float


def run_cell(strategy: str, model: str, level: str, *, limit: int | None = None) -> Cell:
    schema = LADDER[level]
    fn = STRATEGIES[strategy]
    agg = Aggregate()
    book = Ledger()

    for abstract in CORPUS[:limit]:
        try:
            extraction = fn(schema, abstract.text, model=model, callbacks=[book])
            agg.add(score(extraction.value, abstract, schema))
        except Exception as exc:  # a crashed call is an invalid result, not a missing row
            print(f"    ! {abstract.id}: {type(exc).__name__}: {exc}", file=sys.stderr)
            agg.add(score(None, abstract, schema))

    return Cell(
        strategy=strategy,
        model=model,
        level=level,
        n=agg.n,
        validity=agg.validity,
        accuracy=agg.accuracy,
        fabrication_rate=agg.fabrication_rate,
        omission_rate=agg.omission_rate,
        n_nullable=agg.n_nullable,
        n_fabricated=agg.n_fabricated,
        calls=book.n_calls,
        seconds=book.seconds,
    )


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def render(cells: list[Cell], elapsed: float) -> str:
    lines: list[str] = []
    lines.append("# Results\n")
    lines.append(
        "Generated by `projects/p01_structured_output/benchmark.py`. Do not edit by hand.\n"
    )
    lines.append(
        f"{len(cells)} cells, {sum(c.calls for c in cells)} model calls, "
        f"{elapsed / 60:.1f} minutes wall clock.\n"
    )

    lines.append("\n## By strategy, pooled over models and levels\n")
    lines.append("| strategy | valid | accuracy | fabrication | omission | calls |")
    lines.append("|---|---|---|---|---|---|")
    for strategy in STRATEGIES:
        rows = [c for c in cells if c.strategy == strategy]
        if not rows:
            continue
        nullable = sum(r.n_nullable for r in rows)
        fabricated = sum(r.n_fabricated for r in rows)
        n = sum(r.n for r in rows)
        lines.append(
            f"| `{strategy}` | {_pct(sum(r.validity * r.n for r in rows) / n)} "
            f"| {_pct(sum(r.accuracy * r.n for r in rows) / n)} "
            f"| {_pct(fabricated / nullable) if nullable else 'n/a'} "
            f"| {_pct(sum(r.omission_rate * r.n for r in rows) / n)} "
            f"| {sum(r.calls for r in rows)} |"
        )

    lines.append("\n## By schema level\n")
    lines.append("| level | strategy | valid | accuracy | fabrication |")
    lines.append("|---|---|---|---|---|")
    for level in LADDER:
        for strategy in STRATEGIES:
            rows = [c for c in cells if c.level == level and c.strategy == strategy]
            if not rows:
                continue
            n = sum(r.n for r in rows)
            nullable = sum(r.n_nullable for r in rows)
            fabricated = sum(r.n_fabricated for r in rows)
            lines.append(
                f"| {level} | `{strategy}` | {_pct(sum(r.validity * r.n for r in rows) / n)} "
                f"| {_pct(sum(r.accuracy * r.n for r in rows) / n)} "
                f"| {_pct(fabricated / nullable) if nullable else 'n/a'} |"
            )

    lines.append("\n## By model\n")
    lines.append("| model | valid | accuracy | fabrication |")
    lines.append("|---|---|---|---|")
    for model in sorted({c.model for c in cells}):
        rows = [c for c in cells if c.model == model]
        n = sum(r.n for r in rows)
        nullable = sum(r.n_nullable for r in rows)
        fabricated = sum(r.n_fabricated for r in rows)
        lines.append(
            f"| `{model}` | {_pct(sum(r.validity * r.n for r in rows) / n)} "
            f"| {_pct(sum(r.accuracy * r.n for r in rows) / n)} "
            f"| {_pct(fabricated / nullable) if nullable else 'n/a'} |"
        )

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quick", action="store_true", help="one model, two levels, 4 abstracts")
    parser.add_argument("--full", action="store_true", help="the whole grid")
    parser.add_argument("--models", nargs="*", default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable. Start it and try again.", file=sys.stderr)
        return 2

    available = installed_tags()
    fleet = args.models or [m.tag for m in with_role("tools") if m.tag in available]
    if not fleet:
        print("No tool-capable models installed. See the README.", file=sys.stderr)
        return 2

    if args.quick or not args.full:
        fleet, levels, limit = fleet[:1], ["L1_flat", "L4_constrained"], 4
    else:
        levels, limit = list(LADDER), None

    print(f"models: {', '.join(fleet)}")
    print(f"levels: {', '.join(levels)}")

    started = time.perf_counter()
    cells: list[Cell] = []
    for model in fleet:
        for level in levels:
            for strategy in STRATEGIES:
                print(f"  {model} / {level} / {strategy}", flush=True)
                cells.append(run_cell(strategy, model, level, limit=limit))
    elapsed = time.perf_counter() - started

    RAW.write_text(json.dumps([asdict(c) for c in cells], indent=2), encoding="utf-8")
    RESULTS.write_text(render(cells, elapsed), encoding="utf-8")
    print(f"\nwrote {RESULTS.relative_to(Path.cwd())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
